#!/usr/bin/env python3
"""Write colab/train_on_colab.ipynb: a self-contained Colab notebook that
recreates this project on a Colab GPU and trains the submissions there.

The notebook clones the official competition harness at the commit used
locally and embeds this project's own files (submission/*.py and
scripts/build_submission.py) as %%writefile cells, so nothing has to be
uploaded. Re-run this script after editing those files locally.

Usage:
    python scripts/make_colab_notebook.py
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "colab" / "train_on_colab.ipynb"
EMBEDDED = sorted((ROOT / "submission").glob("*.py")) + [
    ROOT / "scripts" / "build_submission.py"]
REPO = "https://github.com/neural-interfaces26/2026-competition.git"


def md(text):
    return {"cell_type": "markdown", "metadata": {},
            "source": text.strip().splitlines(keepends=True)}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None,
            "outputs": [], "source": text.strip().splitlines(keepends=True)}


def main():
    commit = subprocess.run(["git", "-C", str(ROOT / "competition"),
                             "rev-parse", "HEAD"], check=True,
                            capture_output=True, text=True).stdout.strip()
    cells = [
        md("""
# EEG sleep foundation — train on a Colab GPU

Track 03 (Sleep Onset). This notebook rebuilds the project on Colab and trains
the submissions there:

1. **Runtime → Change runtime type → GPU** (T4 is enough), then **Runtime → Run all**.
2. The Muse data (~1.1 GB) is downloaded from NEMAR on the first run and cached
   in Google Drive, so later sessions only extract it.
3. Each finished build (`build/<label>/`, `dist/<label>.zip`, the log) is copied
   to Drive right away, so a disconnect does not lose finished runs.

Generated by `scripts/make_colab_notebook.py`; regenerate it after editing the
solver locally.
"""),
        code("""
!nvidia-smi -L
import torch
print("torch", torch.__version__, "| CUDA:", torch.cuda.is_available())
assert torch.cuda.is_available(), "Select a GPU runtime first."
"""),
        md("## Settings"),
        code(f"""
from pathlib import Path

PROJECT = Path("/content/EEG_sleep_foundation")
COMPETITION_REPO = "{REPO}"
COMPETITION_COMMIT = "{commit}"   # the harness version used locally

USE_DRIVE = True    # cache the data and save the results in Google Drive
DRIVE_DIR = Path("/content/drive/MyDrive/EEG_sleep_foundation")
"""),
        code("""
if USE_DRIVE:
    from google.colab import drive
    drive.mount("/content/drive")
    DRIVE_DIR.mkdir(parents=True, exist_ok=True)
"""),
        md("## Code: official harness + this project's files"),
        code("""
import subprocess
if not (PROJECT / "competition").exists():
    subprocess.run(["git", "clone", "-q", COMPETITION_REPO,
                    str(PROJECT / "competition")], check=True)
subprocess.run(["git", "-C", str(PROJECT / "competition"), "checkout", "-q",
                COMPETITION_COMMIT], check=True)
for sub in ("submission", "scripts", "build", "dist"):
    (PROJECT / sub).mkdir(parents=True, exist_ok=True)
%cd {PROJECT}
"""),
    ]
    for path in EMBEDDED:
        rel = path.relative_to(ROOT).as_posix()
        cells.append(code(f"%%writefile /content/EEG_sleep_foundation/{rel}\n"
                          + path.read_text()))
    cells += [
        md("## Install dependencies (keeps Colab's CUDA torch)"),
        code("""
!pip install -q -r competition/requirements.txt
"""),
        md("## Muse data: from the Drive cache, else download from NEMAR"),
        code("""
DATA = PROJECT / "competition/tracks/sleep_onset/data"
CACHE = DRIVE_DIR / "muse_data.tar" if USE_DRIVE else None

if not (DATA / "neural_compet").exists() and CACHE is not None and CACHE.exists():
    DATA.mkdir(parents=True, exist_ok=True)
    !tar -xf "{CACHE}" -C "{DATA}"
    print("data restored from Drive")

!benchopt prepare competition/tracks/sleep_onset -d Interaxon2026Muse

if CACHE is not None and not CACHE.exists():
    !tar -cf "{CACHE}" -C "{DATA}" neural_compet
    print("data cached in Drive:", CACHE)
"""),
        md("## Smoke test on synthetic data (seconds; the score is meaningless)"),
        code("""
!SLEEP_N_SEEDS=1 python scripts/build_submission.py --solver submission/cnn_gru.py --force 2>&1 | grep -E "CNN-GRU|Error|Ready"
"""),
        md("""
## Train on Muse

Each run trains `Solver.fit` on the GPU, re-runs the exported folder
inference-only (as Codabench does) and writes `dist/<label>.zip`.
`SLEEP_N_SEEDS` = ensemble size, `SLEEP_ADAPT` = per-sleeper adaptation.
Only the `[CNN-GRU ...]` progress lines are shown; the full log goes to
`build/<label>.log`.
"""),
        code("""
import os, shutil

RUNS = [
    # (label,              n_seeds, adapt)
    ("cnn_gru_adapt",      1, True),
    ("cnn_gru_ens_adapt",  5, True),
    ("cnn_gru_ens",        5, False),
]

def build(label, n_seeds, adapt):
    env = {**os.environ, "SLEEP_N_SEEDS": str(n_seeds),
           "SLEEP_ADAPT": "1" if adapt else "0"}
    log_path = PROJECT / "build" / f"{label}.log"
    cmd = ["python", "scripts/build_submission.py", "--data", "muse",
           "--solver", "submission/cnn_gru.py", "--label", label, "--force"]
    with open(log_path, "w") as log:
        proc = subprocess.Popen(cmd, cwd=PROJECT, env=env, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        for line in proc.stdout:
            log.write(line)
            if "CNN-GRU" in line or "Error" in line or "Ready" in line:
                print(line, end="")
    if proc.wait() != 0:
        raise RuntimeError(f"{label} failed; see {log_path}")
    if USE_DRIVE:
        out = DRIVE_DIR / "results"
        out.mkdir(exist_ok=True)
        shutil.copytree(PROJECT / "build" / label, out / label, dirs_exist_ok=True)
        for f in (PROJECT / "build").glob(f"{label}*.*"):
            shutil.copy(f, out)
        shutil.copy(PROJECT / "dist" / f"{label}.zip", out)

for label, n_seeds, adapt in RUNS:
    print(f"===== {label}: {n_seeds} seed(s), adapt={adapt}")
    build(label, n_seeds, adapt)
"""),
        md("## Results (test W-bMAE on the 40 Muse warm-up recordings)"),
        code("""
import re
import pandas as pd

rows = []
for label, n_seeds, adapt in RUNS:
    eval_file = PROJECT / "build" / f"{label}_eval.parquet"
    if not eval_file.exists():
        continue
    d = pd.read_parquet(eval_file).filter(like="objective_").iloc[-1]
    log = (PROJECT / "build" / f"{label}.log").read_text()
    val = re.findall(r"ensemble val W-bMAE ([\\d.]+)", log)
    rows.append({"label": label, "seeds": n_seeds, "adapt": adapt,
                 "val W-bMAE": float(val[-1]) if val else None,
                 "test W-bMAE": d["objective_wbmae_recording_mean"],
                 "bMAE": d["objective_bmae"], "MAE": d["objective_mae"]})
pd.DataFrame(rows).round(1)
"""),
        md("Download a submission ZIP to your computer (also in Drive under `results/`):"),
        code("""
from google.colab import files
files.download(str(PROJECT / "dist" / "cnn_gru_ens_adapt.zip"))
"""),
    ]
    nb = {"cells": cells, "metadata": {
        "accelerator": "GPU",
        "colab": {"provenance": [], "gpuType": "T4"},
        "kernelspec": {"name": "python3", "display_name": "Python 3"},
        "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 0}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(nb, indent=1))
    print(f"wrote {OUT} (harness commit {commit[:7]}, "
          f"{len(EMBEDDED)} embedded files)")


if __name__ == "__main__":
    main()
